using Azure.Identity;
using Azure.Storage.Blobs;
using Azure.Storage.Blobs.Models;
using BugTracker.Application.Tickets;
using Microsoft.Extensions.Options;

namespace BugTracker.Infrastructure.Storage;

/// <summary>Bound from the "Storage" configuration section.</summary>
public sealed class StorageOptions
{
    public const string SectionName = "Storage";

    /// <summary>"Local" (a folder on disk, for development) or "Blob" (Azure Blob Storage).</summary>
    public string Mode { get; set; } = "Local";

    /// <summary>Local mode: folder for files, relative to the API's folder.</summary>
    public string LocalPath { get; set; } = "../../.local/attachments";

    /// <summary>Blob mode: e.g. https://stbt….blob.core.windows.net/ (uses the app's managed identity).</summary>
    public string? BlobEndpoint { get; set; }

    /// <summary>Blob mode alternative: a connection string, e.g. for the Azurite emulator.</summary>
    public string? ConnectionString { get; set; }

    public string Container { get; set; } = "attachments";
}

/// <summary>Development: keeps attachments in a local folder (ignored by Git).</summary>
public sealed class LocalAttachmentStorage : IAttachmentStorage
{
    private readonly string _root;

    public LocalAttachmentStorage(IOptions<StorageOptions> options, Microsoft.Extensions.Hosting.IHostEnvironment environment)
    {
        _root = Path.GetFullPath(Path.Combine(environment.ContentRootPath, options.Value.LocalPath));
        Directory.CreateDirectory(_root);
    }

    public async Task SaveAsync(string path, Stream content, string contentType, CancellationToken ct)
    {
        var full = Resolve(path);
        Directory.CreateDirectory(Path.GetDirectoryName(full)!);
        await using var file = File.Create(full);
        await content.CopyToAsync(file, ct);
    }

    public Task<Stream?> OpenReadAsync(string path, CancellationToken ct)
    {
        var full = Resolve(path);
        return Task.FromResult<Stream?>(File.Exists(full) ? File.OpenRead(full) : null);
    }

    public Task DeleteAsync(string path, CancellationToken ct)
    {
        var full = Resolve(path);
        if (File.Exists(full)) File.Delete(full);
        return Task.CompletedTask;
    }

    /// <summary>Paths are generated by the app, but check anyway that one can't escape the folder.</summary>
    private string Resolve(string path)
    {
        var full = Path.GetFullPath(Path.Combine(_root, path));
        if (!full.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
        {
            throw new InvalidOperationException("Attachment path is outside the storage folder.");
        }
        return full;
    }
}

/// <summary>Azure: keeps attachments in a private blob container, reached with the app's managed identity.</summary>
public sealed class BlobAttachmentStorage : IAttachmentStorage
{
    private readonly BlobContainerClient _container;

    public BlobAttachmentStorage(IOptions<StorageOptions> options)
    {
        var o = options.Value;
        var service = !string.IsNullOrWhiteSpace(o.ConnectionString)
            ? new BlobServiceClient(o.ConnectionString)
            : new BlobServiceClient(
                new Uri(o.BlobEndpoint ?? throw new InvalidOperationException("Storage:BlobEndpoint is not set.")),
                new DefaultAzureCredential());
        _container = service.GetBlobContainerClient(o.Container);
    }

    public async Task SaveAsync(string path, Stream content, string contentType, CancellationToken ct)
    {
        await _container.CreateIfNotExistsAsync(cancellationToken: ct);
        await _container.GetBlobClient(path).UploadAsync(
            content,
            new BlobUploadOptions { HttpHeaders = new BlobHttpHeaders { ContentType = contentType } },
            ct);
    }

    public async Task<Stream?> OpenReadAsync(string path, CancellationToken ct)
    {
        var blob = _container.GetBlobClient(path);
        return await blob.ExistsAsync(ct) ? await blob.OpenReadAsync(cancellationToken: ct) : null;
    }

    public async Task DeleteAsync(string path, CancellationToken ct) =>
        await _container.GetBlobClient(path).DeleteIfExistsAsync(cancellationToken: ct);
}
